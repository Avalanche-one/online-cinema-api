async def get_or_create(session, model, name: str, cache: dict):
    key = (model, name)
    if key in cache:
        return cache[key]

    instance = await session.scalar(select(model).where(model.name == name))

    if instance is None:
        instance = model(name=name)
        session.add(instance)
        await session.flush()

    cache[key] = instance
    return instance


async def seed_database() -> None:
    async with async_session_factory() as session:
        cache: dict = {}

        for data in MOVIES:
            existing_movie = await session.scalar(
                select(Movie).where(
                    Movie.name == data["name"],
                    Movie.year == data["year"],
                    Movie.time == data["time"],
                )
            )
            if existing_movie is not None:
                continue

            certification = await get_or_create(
                session, Certification, data["certification"], cache
            )
            genres = [
                await get_or_create(session, Genre, n, cache) for n in data["genres"]
            ]
            directors = [
                await get_or_create(session, Director, n, cache)
                for n in data["directors"]
            ]
            stars = [
                await get_or_create(session, Star, n, cache) for n in data["stars"]
            ]

            session.add(
                Movie(
                    name=data["name"],
                    year=data["year"],
                    time=data["time"],
                    imdb=data["imdb"],
                    votes=data["votes"],
                    meta_score=data["meta_score"],
                    gross=data["gross"],
                    description=data["description"],
                    price=Decimal(data["price"]),
                    certification=certification,
                    genres=genres,
                    directors=directors,
                    stars=stars,
                )
            )

        await session.commit()


if __name__ == "__main__":
    asyncio.run(seed_database())
